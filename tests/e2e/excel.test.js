// 실제 브라우저(file://, 오프라인) Phase 5a: Excel 파일 선택 → 시트·머리글·자동 매핑·분석·규격 충돌 선택. 가상 자료만 사용.
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright';

const root = path.resolve(import.meta.dirname, '../..');
const meta = JSON.parse(fs.readFileSync(path.join(root, 'dist/build-metadata.json'), 'utf8'));
const fileUrl = pathToFileURL(path.join(root, 'dist', meta.file)).href;
let browser;
before(async () => { browser = await chromium.launch({ headless: true, executablePath: process.env.WAREHOUSE_BROWSER_PATH || undefined }); });
after(async () => { await browser?.close(); });

test('Excel 분석: 가상 XLSX를 읽어 머리글 8행 탐지, 20개 중 매핑 수, 오류·경고, 규격 충돌 선택 후 재분석, 외부 요청 없음', async () => {
  const ctx = await browser.newContext({ offline: true, viewport: { width: 1400, height: 900 } });
  const page = await ctx.newPage();
  const problems = [];
  page.on('pageerror', (e) => problems.push(e.message));
  page.on('request', (r) => !/^(file|data|blob):/.test(r.url()) && problems.push(`network: ${r.url()}`));
  await page.goto(fileUrl);
  await page.waitForFunction(() => window.__warehouseView);
  await page.locator('[data-testid=excel-open]').click();
  await page.locator('[data-testid=excel-file]').setInputFiles(path.join(root, 'fixtures/excel/synthetic-basic.xlsx'));
  await page.waitForFunction(() => /유효/.test(document.querySelector('[data-testid=excel-summary]').textContent));
  assert.equal(await page.locator('[data-testid=excel-header]').inputValue(), '8');
  assert.deepEqual(await page.locator('[data-testid=excel-sheet] option').allTextContents(), ['자재 목록', '참고']);
  const summary = await page.locator('[data-testid=excel-summary]').textContent();
  assert.match(summary, /20개 필드 중 20개 매핑/);
  assert.match(summary, /원본 총면적 336㎡/);
  const issues = await page.locator('[data-testid=excel-issues]').textContent();
  assert.match(issues, /중복 로케이션: 7F-B-10-3-1/);
  assert.match(issues, /7F-A-2 규격 불일치/);
  await page.locator('[data-testid=excel-dims] select').selectOption('1');
  await page.waitForFunction(() => !/7F-A-2 규격 불일치/.test(document.querySelector('[data-testid=excel-issues]').textContent));
  await page.locator('[data-testid=excel-file]').setInputFiles({ name: 'bad.xlsx', mimeType: 'application/octet-stream', buffer: Buffer.from('not a zip') });
  await page.waitForFunction(() => /읽기 실패/.test(document.querySelector('[data-testid=excel-summary]').textContent));
  assert.deepEqual(problems, []);
  await ctx.close();
});

test('Excel 적용(Phase 5b): 배치안 미리보기 → 경고 확인·최종 확인 → AFTER만 변경·자동 백업 → 실행취소 복귀', async () => {
  const ctx = await browser.newContext({ offline: true, viewport: { width: 1400, height: 900 } });
  const page = await ctx.newPage();
  const problems = [];
  page.on('pageerror', (e) => problems.push(e.message));
  page.on('request', (r) => !/^(file|data|blob):/.test(r.url()) && problems.push(`network: ${r.url()}`));
  const dialogs = [];
  page.on('dialog', (d) => { dialogs.push(d.message()); d.accept(); });
  await page.goto(fileUrl);
  await page.waitForFunction(() => window.__warehouseView);
  const before = await page.evaluate(() => JSON.stringify(window.__warehouseSession.state.project.scenarios.before));
  await page.locator('[data-testid=excel-open]').click();
  await page.locator('[data-testid=excel-file]').setInputFiles(path.join(root, 'fixtures/excel/synthetic-basic.xlsx'));
  await page.waitForFunction(() => /유효/.test(document.querySelector('[data-testid=excel-summary]').textContent));
  assert.match(await page.locator('[data-testid=excel-pstats]').textContent(), /치수 충돌을 먼저 해결/);
  assert.ok(await page.locator('[data-testid=excel-apply]').isDisabled());
  await page.locator('[data-testid=excel-dims] select').selectOption('1');
  await page.waitForFunction(() => /오류 행을 수정하거나/.test(document.querySelector('[data-testid=excel-pstats]').textContent));
  await page.locator('[data-testid=excel-config] [name=target]').selectOption('after');
  await page.locator('[data-testid=excel-config] [name=mode]').selectOption('new');
  await page.locator('[data-testid=excel-config] [name=building]').fill('SYN');
  await page.locator('[data-testid=excel-config] [name=source]').fill('가상 자료');
  await page.locator('[data-testid=excel-config] [name=source]').dispatchEvent('change');
  await page.locator('[data-testid=excel-config] [name=skip]').check();
  await page.waitForFunction(() => /적용 후/.test(document.querySelector('[data-testid=excel-pstats]').textContent));
  assert.ok((await page.locator('[data-testid=excel-preview] g[data-id]').count()) > 0);
  const label = await page.locator('[data-testid=excel-apply]').textContent();
  assert.ok(await page.locator('[data-testid=excel-apply]').isDisabled(), '대상 확인 전에는 적용할 수 없다');
  await page.locator('#rTargetConfirm').check();
  if (/경고 확인/.test(label)) {
    assert.ok(await page.locator('[data-testid=excel-apply]').isDisabled());
    await page.locator('#exAllowWarnings').check();
    await page.locator('[data-testid=excel-ack]').check();
  }
  await page.locator('[data-testid=excel-apply]').click();
  await page.waitForFunction(() => window.__warehouseSession.state.project.layoutBackups.length === 1 && window.__warehouseSession.state.status === 'saved');
  const p = await page.evaluate(() => { const p = window.__warehouseSession.state.project; return { racks: p.scenarios.after.objects.filter((o) => o.kind === 'rack').map((o) => o.excel?.key), before: JSON.stringify(p.scenarios.before), backup: p.layoutBackups[0].target, history: p.importHistory.length, scenario: p.settings.scenario }; });
  assert.ok(p.racks.includes('7F-A-1') && p.racks.includes('7F-B-10'));
  assert.equal(p.before, before, 'BEFORE는 변경되지 않는다');
  assert.equal(p.backup, 'after');
  assert.equal(p.history, 1);
  assert.equal(p.scenario, 'after');
  assert.ok(dialogs.some((m) => /AFTER · new · 신규/.test(m)));
  assert.equal(await page.locator('[data-testid=excel-dialog]').evaluate((d) => d.open).catch(() => false), false);
  await page.keyboard.press('Control+z');
  await page.waitForFunction(() => window.__warehouseSession.state.project.importHistory.length === 0);
  assert.deepEqual(problems, []);
  await ctx.close();
});

test('Excel 자동 배치 후보(Phase 6a): 많은 랙을 좁은 창고에 적용하면 선택 후보 이름이 표시·기록되고 모든 랙이 창고 안에 놓인다', async () => {
  const ctx = await browser.newContext({ offline: true, viewport: { width: 1400, height: 900 } });
  const page = await ctx.newPage();
  const problems = [];
  page.on('pageerror', (e) => problems.push(e.message));
  page.on('dialog', (d) => d.accept());
  await page.goto(fileUrl);
  await page.waitForFunction(() => window.__warehouseView);
  await page.locator('[data-testid=excel-open]').click();
  await page.locator('[data-testid=excel-file]').setInputFiles(path.join(root, 'fixtures/excel/synthetic-many.xlsx'));
  await page.waitForFunction(() => /유효/.test(document.querySelector('[data-testid=excel-summary]').textContent));
  const cfg = (n) => page.locator(`[data-testid=excel-config] [name=${n}]`);
  await cfg('target').selectOption('after');
  await cfg('mode').selectOption('new');
  await cfg('building').fill('SYN');
  await cfg('source').fill('가상 자료');
  await cfg('keepManual').uncheck();
  await cfg('preserveStructures').uncheck();
  await cfg('width').fill('12');
  await cfg('depth').fill('8');
  await cfg('depth').dispatchEvent('change');
  await page.waitForFunction(() => /선택 후보: .* 내부 정상 21\/21/.test(document.querySelector('[data-testid=excel-pstats]').textContent));
  const name = (await page.locator('[data-testid=excel-pstats]').textContent()).match(/선택 후보: (.+?) · 내부 정상/)[1];
  assert.notEqual(name, '기존 배치 규칙');
  await page.locator('#rTargetConfirm').check();
  await page.locator('#exAllowWarnings').check();
  await page.waitForFunction(() => /선택 후보: .* 내부 정상 21\/21/.test(document.querySelector('[data-testid=excel-pstats]').textContent));
  await page.locator('[data-testid=excel-ack]').check();
  await page.locator('[data-testid=excel-apply]').click();
  await page.waitForFunction(() => window.__warehouseSession.state.project.layoutBackups.length === 1 && window.__warehouseSession.state.status === 'saved');
  const r = await page.evaluate(() => { const p = window.__warehouseSession.state.project; return { w: p.scenarios.after.warehouse, racks: p.scenarios.after.objects.filter((o) => o.kind === 'rack' && o.excel), cand: p.autoPlacement.history.at(-1).candidate }; });
  assert.equal(r.racks.length, 21);
  for (const o of r.racks) {
    const m = Math.max(o.width, o.depth); // 회전 외곽은 느슨하게 확인
    assert.ok(!o.placementMeta.waiting && o.x >= -m && o.y >= -m && o.x <= r.w.width && o.y <= r.w.height, `${o.code} 창고 밖`);
  }
  assert.equal(r.cand, name);
  assert.deepEqual(problems, []);
  await ctx.close();
});

test('Excel 후보 비교·선택·재최적화(Phase 6b): 비교표 선택은 후보를 다시 만들지 않고 미리보기만 바꾸며 선택 후보가 적용 기록에 남는다', async () => {
  const ctx = await browser.newContext({ offline: true, viewport: { width: 1400, height: 900 } });
  const page = await ctx.newPage();
  const problems = [];
  page.on('pageerror', (e) => problems.push(e.message));
  page.on('dialog', (d) => d.accept());
  await page.goto(fileUrl);
  await page.waitForFunction(() => window.__warehouseView);
  await page.locator('[data-testid=excel-open]').click();
  await page.locator('[data-testid=excel-file]').setInputFiles(path.join(root, 'fixtures/excel/synthetic-many.xlsx'));
  await page.waitForFunction(() => /유효/.test(document.querySelector('[data-testid=excel-summary]').textContent));
  const cfg = (n) => page.locator(`[data-testid=excel-config] [name=${n}]`);
  await cfg('target').selectOption('after');
  await cfg('mode').selectOption('new');
  await cfg('building').fill('SYN');
  await cfg('source').fill('가상 자료');
  await cfg('keepManual').uncheck();
  await cfg('preserveStructures').uncheck();
  await cfg('width').fill('6');
  await cfg('depth').fill('4');
  await cfg('depth').dispatchEvent('change');
  await cfg('allowWarnings').check();
  const rows = page.locator('[data-testid=excel-comparison] tbody tr');
  const stats = () => page.locator('[data-testid=excel-pstats]').textContent();
  await page.waitForFunction(() => document.querySelectorAll('[data-testid=excel-comparison] tbody tr').length === 5);
  const first = await stats();
  const checked = await page.locator('[data-testid=excel-comparison] input:checked').getAttribute('data-cand');
  const other = checked === '0' ? '1' : '0';
  await page.locator(`[data-testid=excel-comparison] input[data-cand="${other}"]`).check();
  assert.notEqual(await stats(), first);
  assert.equal(await rows.count(), 5, '선택은 후보를 다시 만들지 않는다');
  await page.locator(`[data-testid=excel-comparison] input[data-cand="${checked}"]`).check();
  assert.equal(await stats(), first);
  // 선택 범위인데 체크된 랙이 없으면 토스트
  await page.locator('[data-testid=excel-scope]').selectOption('selected');
  await page.locator('[data-testid=excel-optimize]').click();
  await page.waitForFunction(() => /아래 목록에서 재최적화할 랙을 선택하세요\./.test(document.body.textContent));
  assert.equal(await rows.count(), 5);
  // 랙 포커스 → 상세
  await page.locator('[data-testid=excel-list] [data-focus]').first().click();
  assert.match(await page.locator('[data-testid=excel-detail]').textContent(), /미리보기 선택/);
  await page.locator('[data-testid=excel-scope]').selectOption('boundary');
  await page.locator('[data-testid=excel-optimize]').click();
  await page.waitForFunction(() => document.querySelectorAll('[data-testid=excel-comparison] tbody tr').length === 6);
  assert.match(await rows.nth(5).textContent(), /^재최적화 · boundary/);
  assert.equal(await page.locator('[data-testid=excel-comparison] input:checked').getAttribute('data-cand'), '5');
  assert.ok(await page.locator('[data-testid=excel-previous]').isEnabled());
  await page.locator('[data-testid=excel-previous]').click();
  assert.equal(await page.locator('[data-testid=excel-comparison] input:checked').getAttribute('data-cand'), checked);
  assert.match(await page.locator('[data-testid=excel-note]').textContent(), /이전 후보로 돌아왔습니다\./);
  // 후보 선택을 바꾸면 경고 확인이 해제된다 → 다시 확인 후 적용
  await page.locator('[data-testid=excel-comparison] input[data-cand="5"]').check();
  const name = (await stats()).match(/선택 후보: (.+?) · 내부 정상/)[1];
  assert.match(name, /^재최적화 · boundary/);
  assert.equal(await page.locator('[data-testid=excel-ack]').isChecked(), false);
  await page.locator('#rTargetConfirm').check();
  await page.locator('[data-testid=excel-ack]').check();
  await page.locator('[data-testid=excel-apply]').click();
  await page.waitForFunction(() => window.__warehouseSession.state.project.layoutBackups.length === 1 && window.__warehouseSession.state.status === 'saved');
  assert.equal(await page.evaluate(() => window.__warehouseSession.state.project.autoPlacement.history.at(-1).candidate), name);
  assert.deepEqual(problems, []);
  await ctx.close();
});

